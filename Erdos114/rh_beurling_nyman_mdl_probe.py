def write_outputs(results: dict, output_dir: Path, force: bool = False) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    results_path = output_dir / f"{EXPERIMENT_ID}_RESULTS.json"
    report_path = output_dir / f"{EXPERIMENT_ID}_REPORT.md"
    sha_path = output_dir / f"{EXPERIMENT_ID}_RESULTS.sha256"
    for path in (results_path, report_path, sha_path):
        if path.exists() and not force:
            raise FileExistsError(f"{path} already exists; refusing to overwrite immutable artifact")

    summary = summarize(results)
    payload = {**results, "summary": summary}
    results_bytes = json.dumps(payload, indent=2, sort_keys=True).encode("utf-8")
    results_path.write_bytes(results_bytes)
    digest = hashlib.sha256(results_bytes).hexdigest()
    sha_path.write_text(f"{digest}  {results_path.name}\n", encoding="utf-8")
    report_path.write_text(markdown_report(results, summary), encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-dir",
        default=Path(__file__).resolve().parent,
        type=Path,
        help="Directory for RESULTS/REPORT/SHA artifacts.",
    )
    parser.add_argument("--force", action="store_true", help="Overwrite existing artifacts.")
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    results = run_probe(DEFAULT_N_VALUES, DEFAULT_QUANT_BITS)
    write_outputs(results, args.output_dir, force=args.force)
    print(f"wrote {EXPERIMENT_ID} artifacts to {args.output_dir}")


if __name__ == "__main__":
    main()
